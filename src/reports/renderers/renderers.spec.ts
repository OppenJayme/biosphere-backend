import readXlsxFile, { readSheet } from 'read-excel-file/node';
import { CONFIDENTIAL_NOTICE, type ReportDocument } from '../report-document';
import { renderXlsx, uniqueSheetName } from './xlsx.renderer';

const readSheetNames = async (body: Buffer): Promise<string[]> =>
  (await readXlsxFile(body)).map((sheet) => sheet.sheet);

const detail = {
  title: 'Every specimen in the report',
  columns: ['Accession No.', 'Specimen', 'Qty'],
  rows: [
    ['USC-001', 'Stacked one\nStacked two', 1],
    ['USC-002', '=HYPERLINK("x")', null],
  ],
};

const report: ReportDocument = {
  title: 'Inventory Report',
  periodLabel: 'September 2026',
  generatedAt: new Date('2026-09-30T01:00:00.000Z'),
  generatedBy: 'Test Curator',
  confidential: true,
  rowCount: 2,
  blocks: [
    { kind: 'heading', text: 'Summary' },
    { kind: 'paragraph', text: 'Señor Búho counted twice.' },
    { kind: 'keyValues', items: [{ label: 'Specimens', value: 2 }] },
    { kind: 'heading', text: 'Specimens: by area / room' },
    { kind: 'table', table: detail },
    { kind: 'table', table: { title: 'Empty', columns: ['A'], rows: [] } },
  ],
  csvTable: detail,
};

describe('renderXlsx', () => {
  let workbook: Buffer;

  beforeAll(() => {
    workbook = renderXlsx(report);
  });

  it('writes a Summary sheet first, then one sheet per table', async () => {
    expect(workbook.subarray(0, 2).toString('latin1')).toBe('PK');
    expect(await readSheetNames(workbook)).toEqual([
      'Summary',
      'Specimens by area room',
      'Specimens by area room (2)',
    ]);
  });

  it('puts the report details, notes and key figures on the Summary', async () => {
    const rows = (await readSheet(workbook, 'Summary')).map((row) =>
      row.map((cell) => (cell === null ? null : String(cell))),
    );
    expect(rows[0][0]).toBe('Inventory Report');
    expect(rows).toEqual(
      expect.arrayContaining([
        ['Period', 'September 2026'],
        ['Generated by', 'Test Curator'],
        ['Notice', CONFIDENTIAL_NOTICE],
        ['Señor Búho counted twice.', null],
        ['Specimens', '2'],
        [
          'Every specimen in the report',
          'See the "Specimens by area room" sheet (2 rows)',
        ],
      ]),
    );
  });

  it('keeps table cells, line breaks and formula-like text as values', async () => {
    const rows = await readSheet(workbook, 'Specimens by area room');
    expect(rows[0]).toEqual(['Accession No.', 'Specimen', 'Qty']);
    expect(rows[1]).toEqual(['USC-001', 'Stacked one\nStacked two', 1]);
    expect(rows[2]).toEqual(['USC-002', '=HYPERLINK("x")', null]);
  });

  it('shows every detail column in place of the narrowed printed table', async () => {
    const full = {
      columns: ['Accession No.', 'Scientific name', 'Common name', 'Family'],
      rows: [['USC-001', 'Paradoxurus', 'Civet', 'Viverridae']],
    };
    const workbook = renderXlsx({
      ...report,
      blocks: [
        { kind: 'heading', text: 'Specimens' },
        {
          kind: 'table',
          table: {
            columns: ['Accession No.', 'Specimen'],
            rows: [['USC-001', 'Paradoxurus\nCivet']],
          },
        },
      ],
      csvTable: full,
    });

    expect(await readSheetNames(workbook)).toEqual(['Summary', 'Specimens']);
    expect(await readSheet(workbook, 'Specimens')).toEqual([
      full.columns,
      ...full.rows,
    ]);
  });

  it('adds the detail table as its own sheet when no block shows it', async () => {
    const summaryOnly = renderXlsx({
      ...report,
      confidential: false,
      blocks: [{ kind: 'paragraph', text: 'Totals only.' }],
    });
    expect(await readSheetNames(summaryOnly)).toEqual(['Summary', 'Details']);
    const summary = await readSheet(summaryOnly, 'Summary');
    expect(summary.flat()).not.toContain('Notice');
  });
});

describe('uniqueSheetName', () => {
  it('strips characters Excel forbids, cuts to 31 and numbers repeats', () => {
    const used = new Set<string>();
    expect(uniqueSheetName('Visits: [Pending] / *Approved?', used)).toBe(
      'Visits Pending Approved',
    );
    const long = 'A'.repeat(40);
    expect(uniqueSheetName(long, used)).toBe('A'.repeat(31));
    expect(uniqueSheetName(long, used)).toBe(`${'A'.repeat(27)} (2)`);
    expect(uniqueSheetName('   ', used)).toBe('Table');
  });
});
