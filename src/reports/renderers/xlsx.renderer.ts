import { buildXlsx, type XlsxSheet } from '../../common/excel/xlsx-writer';
import {
  CONFIDENTIAL_NOTICE,
  type ReportDocument,
  type ReportTable,
} from '../report-document';
import {
  REPORT_INSTITUTION,
  REPORT_MUSEUM,
  formatGeneratedAt,
} from './render-helpers';

const SUMMARY_SHEET = 'Summary';
const MAX_SHEET_NAME = 31;

/**
 * Excel is the museum's only report format (2026-11-12). The first sheet
 * carries the report's heading details, key figures and notes in reading
 * order; each table gets its own sheet so it can be sorted and filtered.
 */
export function renderXlsx(document: ReportDocument): Buffer {
  const names = new Set([SUMMARY_SHEET.toLowerCase()]);
  const summary: XlsxSheet = {
    name: SUMMARY_SHEET,
    header: [document.title, ''],
    rows: [
      ['Institution', `${REPORT_INSTITUTION}, ${REPORT_MUSEUM}`],
      ['Period', document.periodLabel],
      ['Generated', formatGeneratedAt(document.generatedAt)],
      ['Generated by', document.generatedBy],
    ],
  };
  if (document.confidential) {
    summary.rows.push(['Notice', CONFIDENTIAL_NOTICE]);
  }

  const tableSheets: XlsxSheet[] = [];
  const addTable = (table: ReportTable, preferredName: string): string => {
    const name = uniqueSheetName(preferredName, names);
    tableSheets.push({ name, header: table.columns, rows: table.rows });
    return name;
  };

  // Builders print a narrowed, untitled copy of the detail table (two fields
  // stacked per cell) to fit portrait pages. A spreadsheet has room for every
  // column, so the full detail table takes its place.
  const detail = document.csvTable;
  const isPrintedDetail = (table: ReportTable) =>
    !!detail &&
    table !== detail &&
    table.title === undefined &&
    table.rows.length === detail.rows.length;
  let detailShown = false;

  let lastHeading = '';
  for (const block of document.blocks) {
    switch (block.kind) {
      case 'heading':
        lastHeading = block.text;
        summary.rows.push([null, null], [block.text, null]);
        break;
      case 'paragraph':
        summary.rows.push([block.text, null]);
        break;
      case 'keyValues':
        for (const item of block.items) {
          summary.rows.push([item.label, item.value]);
        }
        break;
      case 'table': {
        const table =
          detail && isPrintedDetail(block.table) ? detail : block.table;
        if (table === detail) {
          if (detailShown) break;
          detailShown = true;
        }
        const name = addTable(table, lastHeading || table.title || 'Table');
        summary.rows.push([
          table.title ?? 'Table',
          `See the "${name}" sheet (${table.rows.length} rows)`,
        ]);
        break;
      }
    }
  }

  if (detail && !detailShown) {
    const name = addTable(detail, 'Details');
    summary.rows.push(
      [null, null],
      ['Details', `See the "${name}" sheet (${detail.rows.length} rows)`],
    );
  }

  return buildXlsx([summary, ...tableSheets]).body;
}

/** A valid, unique Excel sheet name (31 characters, no []:*?/\). */
export function uniqueSheetName(preferred: string, used: Set<string>): string {
  const base =
    preferred
      .replace(/[[\]:*?/\\]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .replace(/^'+|'+$/g, '')
      .slice(0, MAX_SHEET_NAME)
      .trim() || 'Table';
  let name = base;
  for (let n = 2; used.has(name.toLowerCase()); n += 1) {
    const suffix = ` (${n})`;
    name = base.slice(0, MAX_SHEET_NAME - suffix.length).trim() + suffix;
  }
  used.add(name.toLowerCase());
  return name;
}
